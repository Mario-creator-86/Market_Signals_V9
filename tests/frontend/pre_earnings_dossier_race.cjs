const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('frontend/app.js', 'utf8');
const start = source.indexOf('UI.loadPreEarningsDossier = async function');
const end = source.indexOf('UI.renderPreEarningsDossier = function', start);
const pending = [];
const renders = [];
let body = {getAttribute: () => 'TEST', innerHTML: ''};
const UI = {renderPreEarningsDossier: p => renders.push(p)};
const API = {getPreEarningsDossier: (symbol, event) => new Promise(resolve => pending.push({resolve, event})), _warnNetworkOnce: () => {}};
vm.runInNewContext(source.slice(start, end), {UI, API, document: {getElementById: () => body}});
(async () => {
  const old = UI.loadPreEarningsDossier('TEST', '2026-09-10T20:00:00Z');
  body = {getAttribute: () => 'TEST', innerHTML: ''};
  const latest = UI.loadPreEarningsDossier('TEST', '2026-09-11T20:00:00Z');
  pending[1].resolve({earnings_time_utc: pending[1].event});
  await latest;
  pending[0].resolve({earnings_time_utc: pending[0].event});
  await old;
  assert.equal(renders.length, 1);
  assert.equal(renders[0].earnings_time_utc, pending[1].event);
  const mismatch = UI.loadPreEarningsDossier('TEST', '2026-09-12T20:00:00Z');
  pending[2].resolve({earnings_time_utc: '2026-09-11T20:00:00Z'});
  await mismatch;
  assert.equal(renders.length, 1);
  assert.match(body.innerHTML, /unavailable/);
  console.log('Pre-Earnings dossier race and event mismatch checks passed');
})().catch(error => {console.error(error); process.exitCode = 1;});
