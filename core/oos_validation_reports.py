"""Read-only, safe presentation of reproducible OOS validation artifacts.

The validator writes immutable-ish JSON reports under ``output/``.  This module
turns those artifacts into a small API payload without treating price-only
research as permission to trade: timestamped historical news is not available
in these reports, so autonomous eligibility always remains false here.
"""

from __future__ import annotations

import json
import hashlib
import os
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Tuple


PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_REPORT_DIR = PROJECT_ROOT / "output"
_REPORT_GLOB = "oos_validation_*.json"


def _report_directory() -> Path:
    configured = str(os.getenv("MS_OOS_REPORTS_DIR", "")).strip()
    return Path(configured) if configured else DEFAULT_REPORT_DIR


def _parse_timestamp(value: Any) -> datetime:
    try:
        text = str(value or "").replace("Z", "+00:00")
        parsed = datetime.fromisoformat(text)
        if parsed.tzinfo is None:
            parsed = parsed.replace(tzinfo=timezone.utc)
        return parsed.astimezone(timezone.utc)
    except (TypeError, ValueError):
        return datetime.min.replace(tzinfo=timezone.utc)


def _string(value: Any, default: str = "") -> str:
    return str(value) if value is not None else default


def _public_trade(row: Any) -> Optional[Dict[str, Any]]:
    if not isinstance(row, dict):
        return None
    allowed = (
        "ticker",
        "dir",
        "entry",
        "exit",
        "reason",
        "r",
        "r_net",
        "net_pct",
        "score",
        "mode",
        "profile",
        "strategy_source",
        "entry_time",
        "exit_time",
    )
    return {key: row.get(key) for key in allowed if key in row}


def _public_report(report: Dict[str, Any], provenance: Dict[str, Any], generated_at: Any) -> Optional[Dict[str, Any]]:
    ticker = _string(report.get("ticker")).upper().strip()
    if not ticker:
        return None
    metrics = report.get("metrics") if isinstance(report.get("metrics"), dict) else {}
    source_data = report.get("source_data") if isinstance(report.get("source_data"), dict) else {}
    thresholds = report.get("thresholds") if isinstance(report.get("thresholds"), dict) else {}
    trades = [item for item in (_public_trade(row) for row in report.get("oos_trades", [])) if item is not None]
    report_provenance = provenance if isinstance(provenance, dict) else {}
    report_cost_model = report_provenance.get("cost_model")
    if not isinstance(report_cost_model, dict) and isinstance(report.get("cost_model"), dict):
        report_cost_model = report.get("cost_model")
    # Reports written before audit provenance was introduced may be useful for
    # local investigation, but they cannot substantiate a customer-facing OOS
    # claim because their exact code/config and received data span are unknown.
    required_source = {"actual_start", "actual_end", "received_bars"}
    required_provenance = {
        "strategy_backtester_sha256",
        "walk_forward_validation_sha256",
        "config_sha256",
    }
    if not required_source.issubset(source_data) or not required_provenance.issubset(report_provenance):
        return None
    try:
        replay_source = Path(__file__).with_name("strategy_backtester.py")
        validator_source = Path(__file__).with_name("walk_forward_validation.py")
        current_replay_hash = hashlib.sha256(replay_source.read_bytes()).hexdigest()
        current_validator_hash = hashlib.sha256(validator_source.read_bytes()).hexdigest()
    except OSError:
        return None
    if (
        report_provenance.get("strategy_backtester_sha256") != current_replay_hash
        or report_provenance.get("walk_forward_validation_sha256") != current_validator_hash
    ):
        # A report generated by different replay code cannot substantiate the
        # behavior of the build currently shown to customers.
        return None
    return {
        "ticker": ticker,
        "status": _string(report.get("status"), "unknown"),
        "reason": _string(report.get("reason"), "No validation reason was recorded."),
        "method": _string(report.get("method"), "unknown"),
        "as_of": report.get("as_of"),
        "generated_at": generated_at,
        "metrics": {
            key: metrics.get(key)
            for key in (
                "sample_size", "wins", "losses", "win_rate", "profit_factor",
                "expectancy_r", "expectancy_pct", "net_pct", "raw_max_drawdown_pct",
                "capital_risk_per_trade_pct", "capital_equity_start", "capital_equity_end",
                "capital_return_pct", "capital_equity_model", "max_drawdown_pct",
            )
            if key in metrics
        },
        "thresholds": {
            key: thresholds.get(key)
            for key in (
                "min_windows", "min_sample", "min_profit_factor",
                "min_expectancy_r", "max_drawdown_pct",
            )
            if key in thresholds
        },
        "source_data": {
            key: source_data.get(key)
            for key in (
                "source", "symbol", "interval", "requested_days", "requested_start",
                "requested_end", "actual_start", "actual_end", "actual_span_days",
                "expected_bars", "received_bars", "source_truncated",
            )
            if key in source_data
        },
        "limitations": [str(item) for item in report.get("limitations", []) if isinstance(item, str)],
        "capital_model": report.get("capital_model") if isinstance(report.get("capital_model"), dict) else {},
        "closed_oos_trades": trades,
        "replay_provenance": {
            key: report_provenance.get(key)
            for key in (
                "replay", "strategy_backtester_sha256", "walk_forward_validation_sha256", "config_sha256",
                "historical_news", "agents_risk",
            )
            if key in report_provenance
        } | ({"cost_model": report_cost_model} if isinstance(report_cost_model, dict) else {}),
        # A price-only OOS result cannot prove that live news context was safe.
        # This flag is intentionally independent from a report's price status.
        "autonomous_execution_eligible": False,
        "autonomous_execution_reason": (
            "Price/volume OOS evidence does not replay timestamped historical news. "
            "The live fresh-news and realized-capital guards remain required."
        ),
    }


def _load_reports(directory: Path) -> Iterable[Tuple[datetime, Dict[str, Any], Dict[str, Any], Any]]:
    if not directory.is_dir():
        return []
    loaded: List[Tuple[datetime, Dict[str, Any], Dict[str, Any], Any]] = []
    for path in directory.glob(_REPORT_GLOB):
        try:
            with path.open("r", encoding="utf-8") as handle:
                payload = json.load(handle)
            reports = payload.get("reports") if isinstance(payload, dict) else None
            if not isinstance(reports, list):
                continue
            generated_at = payload.get("generated_at")
            when = _parse_timestamp(generated_at)
            if when == datetime.min.replace(tzinfo=timezone.utc):
                when = datetime.fromtimestamp(path.stat().st_mtime, tz=timezone.utc)
                generated_at = when.isoformat()
            provenance = payload.get("replay_provenance") if isinstance(payload, dict) else {}
            for report in reports:
                if isinstance(report, dict):
                    loaded.append((when, report, provenance if isinstance(provenance, dict) else {}, generated_at))
        except (OSError, ValueError, TypeError, json.JSONDecodeError):
            continue
    return loaded


def get_latest_oos_validation_reports(output_dir: Optional[Path] = None) -> Dict[str, Any]:
    """Return the newest report per ticker, or an explicit no-data response."""
    directory = output_dir or _report_directory()
    latest_by_ticker: Dict[str, Tuple[datetime, Dict[str, Any]]] = {}
    for when, raw_report, provenance, generated_at in _load_reports(directory):
        public = _public_report(raw_report, provenance, generated_at)
        if public is None:
            continue
        ticker = public["ticker"]
        existing = latest_by_ticker.get(ticker)
        if existing is None or when > existing[0]:
            latest_by_ticker[ticker] = (when, public)

    reports = [item[1] for item in sorted(latest_by_ticker.values(), key=lambda item: item[1]["ticker"])]
    if not reports:
        return {
            "status": "no_reports",
            "reports": [],
            "autonomous_execution_eligible": False,
            "reason": "No reproducible fixed-configuration OOS report is available yet.",
        }
    newest = max((item[0] for item in latest_by_ticker.values()), default=None)
    return {
        "status": "available",
        "generated_at": newest.isoformat() if newest is not None else None,
        "report_count": len(reports),
        "reports": reports,
        "autonomous_execution_eligible": False,
        "reason": (
            "These are price/volume OOS research reports only. Autonomous execution also requires "
            "the separate realized-capital and fresh-news guards."
        ),
    }
